CREATE TABLE IF NOT EXISTS packs (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 description TEXT NOT NULL,
 level VARCHAR(16) NOT NULL DEFAULT 'BASIC',
 active TINYINT(1) NOT NULL DEFAULT 1,
 duration_days INT NOT NULL DEFAULT 30,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pack_rules (
 pack_id INT NOT NULL,
 scope VARCHAR(16) NOT NULL,
 kind VARCHAR(16) NOT NULL,
 reference_id INT NOT NULL DEFAULT 0,
 PRIMARY KEY (pack_id,scope,kind,reference_id),
 CONSTRAINT fk_pack_rules_pack FOREIGN KEY (pack_id) REFERENCES packs(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS client_packs (
 client_id INT NOT NULL PRIMARY KEY,
 pack_id INT NOT NULL,
 expires_at DATETIME DEFAULT NULL,
 KEY idx_client_pack (pack_id),
 CONSTRAINT fk_client_packs_pack FOREIGN KEY (pack_id) REFERENCES packs(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
